import type { TargetedDragEvent } from 'preact';
import { useRef, useState } from 'preact/hooks';

import { UploadIcon } from '../components/icons';
import { useApp } from '../context';
import { readStatementFile, sampleRows, sampleStatement } from '../import-file';
import { SAMPLE_FILE_NAME } from '../../sample';

export function StartView() {
  const { dispatch } = useApp();
  const inputRef = useRef<HTMLInputElement>(null);
  const [error, setError] = useState('');
  const [busy, setBusy] = useState(false);
  const [dragging, setDragging] = useState(false);

  const open = async (file: File | undefined) => {
    if (!file) return;
    setError('');
    setBusy(true);
    const result = await readStatementFile(file);
    setBusy(false);
    if (!result.ok) {
      setError(result.error);
      return;
    }
    dispatch({
      type: 'file-read',
      fileName: file.name,
      source: result.source,
      fileRows: result.fileRows,
    });
  };

  const onDrop = (event: TargetedDragEvent<HTMLDivElement>) => {
    event.preventDefault();
    setDragging(false);
    void open(event.dataTransfer?.files[0]);
  };

  return (
    <div class="start">
      <section class="start-intro">
        <h1 tabIndex={-1}>See where your money went, without sending your statement anywhere</h1>
        <p class="lead">
          Open a bank or UPI statement export and get monthly totals, categories, top merchants and
          a few patterns worth a second look. The file is read by this page, on this device. There
          is no server, no account and no tracking.
        </p>
      </section>

      <section class="start-actions" aria-label="Open a statement">
        <div
          class={dragging ? 'dropzone dropzone-active' : 'dropzone'}
          onDragOver={(event) => {
            event.preventDefault();
            setDragging(true);
          }}
          onDragLeave={() => setDragging(false)}
          onDrop={onDrop}
        >
          <UploadIcon />
          <p class="dropzone-title">Drop a statement here</p>
          <p class="dropzone-hint">
            CSV works best. A PDF works only if its text can be selected; scanned and
            password-protected PDFs are not supported.
          </p>
          <button
            type="button"
            class="button button-primary"
            disabled={busy}
            onClick={() => inputRef.current?.click()}
          >
            {busy ? 'Reading the file…' : 'Choose a file'}
          </button>
          <input
            ref={inputRef}
            class="visually-hidden"
            type="file"
            accept=".csv,.tsv,.txt,.pdf,text/csv,application/pdf"
            aria-label="Statement file"
            tabIndex={-1}
            onChange={(event) => {
              const input = event.currentTarget;
              void open(input.files?.[0]);
              input.value = '';
            }}
          />
          {error ? (
            <p class="form-error" role="alert">
              {error}
            </p>
          ) : null}
        </div>

        <div class="sample-box">
          <h2>No statement to hand?</h2>
          <p>
            Try it with a made-up statement: six months of invented transactions from fictional
            merchants, generated by a script in this project.
          </p>
          <div class="button-row">
            <button
              type="button"
              class="button button-secondary"
              onClick={() =>
                dispatch({
                  type: 'statement-loaded',
                  statement: sampleStatement(),
                  saveProfile: null,
                })
              }
            >
              Try with sample data
            </button>
            <button
              type="button"
              class="button button-quiet"
              onClick={() =>
                dispatch({
                  type: 'file-read',
                  fileName: SAMPLE_FILE_NAME,
                  source: 'sample',
                  fileRows: sampleRows(),
                })
              }
            >
              Show me the import steps
            </button>
          </div>
        </div>
      </section>

      <section class="start-notes">
        <div class="note">
          <h2>Before you open a file</h2>
          <p>
            If your export has columns for account number, card number, customer ID, PAN or Aadhaar,
            delete them first. This app never asks for those and has no use for them.
          </p>
          <p>
            As a second line of defence, only the columns you map (date, narration, amounts,
            balance) are read. Every other column is left behind, and card or account fragments
            inside narrations are removed.
          </p>
        </div>
        <div class="note">
          <h2>What stays in this browser</h2>
          <ul class="plain-list">
            <li>Your transactions: in memory only. Close or reload the tab and they are gone.</li>
            <li>
              Your category rules, category choices and column mappings: in this browser's local
              storage, so they are there next time. You can export or delete them.
            </li>
            <li>
              Nothing else, anywhere. The page is built so that it cannot contact a server: the "How
              it works" tab shows how to check that yourself.
            </li>
          </ul>
        </div>
      </section>
    </div>
  );
}
